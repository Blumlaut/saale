/**
 * A minimal stdio MCP server for tests.
 *
 * Writes a Node script that answers the handshake, `tools/list` and
 * `tools/call` over stdin/stdout — JSON-RPC framed one message per line, the
 * way an MCP server on stdio speaks — so a test can drive the real pipe
 * through `sandbox-exec` without installing a package. Its instructions carry
 * the directory it was started in, which is how a test checks the working
 * directory reached the command.
 */

import { writeFile } from "node:fs/promises";
import path from "node:path";

export interface FakeStdioServerOptions {
  /** The name the server reports in `initialize`. */
  name?: string;
  tools?: { name: string; description: string }[];
  /** Write this to stderr and exit instead of serving, for a command that fails. */
  failWith?: string;
  /** Report the value of this variable as the server's name, to see the env arrive. */
  envName?: string;
  /** Write this file when the program runs, so a test can see it started. */
  markerPath?: string;
}

/** The script's file name inside the directory the test owns. */
const SCRIPT_NAME = "fake-stdio-mcp-server.mjs";

/**
 * Write the server into `dir` and return the command that starts it.
 *
 * The path is absolute: the workspace root is the same path in the app and in
 * the container, so a command typed like the ones the settings page accepts can
 * name it.
 */
export async function writeFakeStdioMcpServer(
  dir: string,
  options: FakeStdioServerOptions = {},
): Promise<string> {
  const file = path.join(dir, SCRIPT_NAME);
  await writeFile(file, script(options), "utf8");
  return `node ${file}`;
}

function script(options: FakeStdioServerOptions): string {
  const config = JSON.stringify({
    name: options.name ?? "fake-stdio",
    tools: options.tools ?? [{ name: "echo", description: "Repeat what it was given" }],
    failWith: options.failWith ?? null,
    envName: options.envName ?? null,
    marker: options.markerPath ?? null,
  });

  return `// generated by __tests__/helpers/fake-stdio-mcp-server.ts
import { writeFileSync } from "node:fs";

const config = ${config};

// A marker the test can read: the program itself ran, not just its config.
if (config.marker) writeFileSync(config.marker, "started");

if (config.failWith) {
  process.stderr.write(config.failWith + "\\n");
  process.exit(1);
}

const serverName = config.envName ? (process.env[config.envName] ?? "variable unset") : config.name;

const send = (message) => process.stdout.write(JSON.stringify(message) + "\\n");
const reply = (id, result) => send({ jsonrpc: "2.0", id, result });

let buffer = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", (chunk) => {
  buffer += chunk;
  let index;
  while ((index = buffer.indexOf("\\n")) !== -1) {
    const line = buffer.slice(0, index).trim();
    buffer = buffer.slice(index + 1);
    if (!line) continue;
    const message = JSON.parse(line);
    // A notification has no id and must not be answered.
    if (message.id === undefined) continue;
    switch (message.method) {
      case "initialize":
        reply(message.id, {
          protocolVersion: message.params.protocolVersion,
          capabilities: { tools: {} },
          serverInfo: { name: serverName, version: "1.0.0" },
          instructions: process.cwd(),
        });
        break;
      case "tools/list":
        reply(message.id, {
          tools: config.tools.map((tool) => ({
            name: tool.name,
            description: tool.description,
            inputSchema: { type: "object", properties: {} },
          })),
        });
        break;
      case "tools/call":
        reply(message.id, {
          content: [{ type: "text", text: "called " + message.params.name }],
        });
        break;
      default:
        reply(message.id, {});
    }
  }
});
process.stdin.on("end", () => process.exit(0));
`;
}
